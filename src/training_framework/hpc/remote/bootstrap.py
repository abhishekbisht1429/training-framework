"""Generates `bootstrap.py` (building block B10): one standard-library file
bundling the same modules the workstation uses, so lease, probe, filesystem,
and preflight logic exist once."""

from __future__ import annotations

import inspect
import re

from training_framework.hpc import EXECUTION_PROTOCOL_VERSION
from training_framework.hpc.remote import bootstrap_main, lease, preflight, runtime

_PACKAGE_IMPORT = re.compile(r"^from training_framework\.hpc(\.\w+)+ import .*$", re.MULTILINE)
BUNDLED_MODULES = (runtime, lease, preflight, bootstrap_main)


def render_bootstrap() -> str:
    parts = [
        "#!/usr/bin/env python3",
        '"""Generated by training_framework.hpc; do not edit."""',
        f"PROTOCOL_VERSION = {EXECUTION_PROTOCOL_VERSION}",
    ]
    for module in BUNDLED_MODULES:
        source = _PACKAGE_IMPORT.sub("", inspect.getsource(module))
        parts.append(f"# --- {module.__name__} ---\n{source}")
    parts.append('if __name__ == "__main__":\n    sys.exit(main())')
    return "\n\n".join(parts) + "\n"
